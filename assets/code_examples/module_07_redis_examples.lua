-- Module 07: Production-Grade Redis Lua Scripting Examples & Reference
--
-- This file provides production-ready, battle-tested Redis Lua scripts for core
-- caching and coordination patterns:
--
--  1. Atomic Sliding-Window Rate Limiter (with unique nonce member collision fix)
--  2. Safe Distributed Lock Release (owner-token verification prevents race conditions)
--  3. Probabilistic Early Recomputation / Cache Stampede Defense (XFetch / PER)
--  4. Versioned Compare-and-Set Cache Write-Back (stale write mitigation)
--
-- Operational Invariants & Redis Execution Rules:
--  - Redis executes Lua scripts as a single atomic unit. No other script or command
--    can execute concurrently on the same Redis shard while a script is running.
--  - Scripts must be deterministic and fast: avoid unbounded loops or heavy scans.
--  - KEYS and ARGV convention: Keys accessed by the script MUST be passed via the
--    KEYS array (not hardcoded in the script body) to support Redis Cluster routing.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Atomic Sliding-Window Rate Limiter with Unique Member Invariant
-- -----------------------------------------------------------------------------
-- KEYS[1]: Rate limiter Sorted Set key (e.g., 'rate_limit:users:user_1024:api')
-- ARGV[1]: Current UNIX epoch millisecond timestamp (number, e.g., 1700000000000)
-- ARGV[2]: Sliding window duration in milliseconds (number, e.g., 60000 for 1 minute)
-- ARGV[3]: Max allowed requests per window (number, e.g., 100)
-- ARGV[4]: Unique request nonce / requestId (string, e.g., 'req_uuid_9a8b7c')
--
-- Returns: table {allowed (1 or 0), remaining_quota, retry_after_ms}
local function sliding_window_rate_limiter()
    local key = KEYS[1]
    local now = tonumber(ARGV[1])
    local window = tonumber(ARGV[2])
    local limit = tonumber(ARGV[3])
    local requestId = ARGV[4]

    local clearBefore = now - window

    -- 1. Evict timestamps older than the sliding window: O(log(M) + K)
    redis.call('ZREMRANGEBYSCORE', key, '-inf', clearBefore)

    -- 2. Query current request count within the active window: O(1)
    local currentCount = redis.call('ZCARD', key)

    if currentCount < limit then
        -- 3. Invariant: Member MUST combine timestamp and unique nonce (now:requestId)
        -- Using 'now' alone causes member collision on identical millisecond timestamps,
        -- updating the score instead of adding a new member and allowing limit bypass!
        local uniqueMember = now .. ':' .. requestId
        redis.call('ZADD', key, now, uniqueMember)

        -- 4. Set TTL to clean up idle keys once window elapses
        redis.call('PEXPIRE', key, window + 1000)

        local remaining = limit - currentCount - 1
        return {1, remaining, 0}
    else
        -- Request denied: Calculate when the oldest request in the window expires
        local oldest = redis.call('ZRANGE', key, 0, 0, 'WITHSCORES')
        local retryAfter = 0
        if #oldest > 0 then
            local oldestScore = tonumber(oldest[2])
            retryAfter = math.max(0, (oldestScore + window) - now)
        else
            retryAfter = window
        end
        return {0, 0, retryAfter}
    end
end

-- -----------------------------------------------------------------------------
-- 2. Safe Distributed Lock Release (Owner-Token Verification)
-- -----------------------------------------------------------------------------
-- Problem: If Client A acquires a lock with a 30s lease, encounters an unexpected
-- 35s JVM GC pause or network stall, its lease expires. Client B acquires the lock.
-- Client A wakes up and naively issues 'DEL lock:order:123', accidentally releasing
-- Client B's lock!
--
-- Solution: Client A stores a unique random UUID as the lock value ('SET key token NX PX ttl').
-- Upon release, this atomic script deletes the key ONLY if the stored token matches
-- Client A's token.
--
-- KEYS[1]: Lock key (e.g., 'lock:orders:ord_9988')
-- ARGV[1]: Lock owner token (unique UUID generated by the holding client)
--
-- Returns: 1 if the lock was owned and deleted; 0 if the token mismatched or key expired.
local function safe_distributed_lock_release()
    local currentToken = redis.call('GET', KEYS[1])
    if currentToken == ARGV[1] then
        return redis.call('DEL', KEYS[1])
    else
        return 0
    end
end

-- -----------------------------------------------------------------------------
-- 3. Probabilistic Early Expiration (XFetch / PER Algorithm)
-- -----------------------------------------------------------------------------
-- Problem: Cache stampede occurs when a hot cached item expires and thousands of
-- concurrent requests miss simultaneously, crushing the database.
--
-- Solution: The XFetch / Probabilistic Early Refresh algorithm refreshes the cache
-- *before* it expires with an exponentially increasing probability as TTL nears zero.
--
-- Formula: Refresh early if: -(beta * delta * math.log(random())) > remaining_ttl_seconds
-- Where:
--   beta  > 0 (aggressiveness parameter, default = 1.0)
--   delta = computation/read duration in seconds (recorded on last compute)
--
-- KEYS[1]: Cache entry key (holds the serialized payload)
-- KEYS[2]: Cache metadata key (hash holding 'ttl_expires_at', 'compute_delta_sec')
-- ARGV[1]: Current UNIX epoch timestamp in seconds (e.g., 1700000000)
-- ARGV[2]: Aggressiveness factor beta (e.g., 1.0)
-- ARGV[3]: Random float uniform in (0, 1] passed from client (e.g., math.random())
--
-- Returns: table {status ('VALID', 'REFRESH_REQUIRED', 'MISS'), value}
local function xfetch_probabilistic_refresh()
    local dataKey = KEYS[1]
    local metaKey = KEYS[2]
    local now = tonumber(ARGV[1])
    local beta = tonumber(ARGV[2]) or 1.0
    local rnd = tonumber(ARGV[3]) or 0.5

    local value = redis.call('GET', dataKey)
    if not value then
        return {'MISS', nil}
    end

    local meta = redis.call('HMGET', metaKey, 'expires_at', 'compute_delta')
    if not meta[1] or not meta[2] then
        -- No metadata available, treat as valid cached value
        return {'VALID', value}
    end

    local expiresAt = tonumber(meta[1])
    local delta = tonumber(meta[2])
    local remainingTtl = expiresAt - now

    if remainingTtl <= 0 then
        -- Hard expiration reached
        return {'MISS', nil}
    end

    -- Probabilistic early recomputation threshold check
    -- Note: math.log in Lua computes natural logarithm (ln)
    local earlyTrigger = -(beta * delta * math.log(rnd))

    if earlyTrigger > remainingTtl then
        -- High traffic has probabilistically triggered a background refresh!
        -- The caller should compute fresh data asynchronously while still
        -- serving the currently valid cached value.
        return {'REFRESH_REQUIRED', value}
    else
        return {'VALID', value}
    end
end

-- -----------------------------------------------------------------------------
-- 4. Versioned Compare-and-Set Cache Write-Back
-- -----------------------------------------------------------------------------
-- Problem: Invalidation race condition:
-- 1. Thread A reads Version 1 from DB.
-- 2. Thread B updates DB to Version 2 and evicts cache.
-- 3. Thread A (pre-empted) writes back Version 1, corrupting the cache.
--
-- Solution: This script compares the new entity version against the currently
-- cached version. The cache is updated ONLY if new_version > existing_version.
--
-- KEYS[1]: Cache key (e.g., 'cache:user:101')
-- ARGV[1]: New payload JSON (string)
-- ARGV[2]: New version number (integer or timestamp)
-- ARGV[3]: TTL in seconds (integer)
--
-- Returns: 1 if updated, 0 if rejected as stale
local function versioned_cache_put()
    local key = KEYS[1]
    local newPayload = ARGV[1]
    local newVersion = tonumber(ARGV[2])
    local ttlSeconds = tonumber(ARGV[3])

    local existingVersionStr = redis.call('HGET', key, '_version')
    if existingVersionStr then
        local existingVersion = tonumber(existingVersionStr)
        if existingVersion and newVersion <= existingVersion then
            -- Reject stale write: current cache has newer or equal version!
            return 0
        end
    end

    -- Update hash with payload and version atomically
    redis.call('HSET', key, '_data', newPayload, '_version', newVersion)
    redis.call('EXPIRE', key, ttlSeconds)
    return 1
end

